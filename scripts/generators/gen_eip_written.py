def generate_eip_written_massive():
    """2020~2026년 7개 연도 x 100문항 = 총 700문항 완전체 생성"""
    years = [2026, 2025, 2024, 2023, 2022, 2021, 2020]
    all_questions = []

    sub_configs = [
        (1, "1과목 소프트웨어 설계", SUB1_BANK),
        (2, "2과목 소프트웨어 개발", SUB2_BANK),
        (3, "3과목 데이터베이스 구축", SUB3_BANK),
        (4, "4과목 프로그래밍 언어 활용", SUB4_BANK),
        (5, "5과목 정보시스템 구축관리", SUB5_BANK)
    ]

    total_global_idx = 1

    for y_idx, year in enumerate(years):
        session_title = f"{year}년 제1회 정기기출 풀세트"
        year_q_num = 1

        for sub_id, sub_name, bank in sub_configs:
            # 20문항씩 선택/배치
            bank_len = len(bank)
            for i in range(20):
                # 연도별로 오프셋을 두어 다양한 문제 배치
                item_idx = (y_idx * 3 + i) % bank_len
                raw_item = bank[item_idx]

                q_id = f"eip-written-{year}-{year_q_num:03d}"
                all_questions.append({
                    "id": q_id,
                    "year": year,
                    "session": session_title,
                    "type": "multiple_choice",
                    "subject_id": sub_id,
                    "subject_name": sub_name,
                    "chapter": sub_name,
                    "question": f"[{sub_name}] {raw_item['q']}",
                    "code_snippet": raw_item.get("code"),
                    "options": raw_item["opts"],
                    "answer": raw_item["ans"],
                    "correct_answer": raw_item["ans"],
                    "accepted_answers": None,
                    "explanation": raw_item["exp"]
                })
                year_q_num += 1
                total_global_idx += 1

    return all_questions

if __name__ == "__main__":
    qs = generate_eip_written_massive()
    print(f"Total eip_written questions generated: {len(qs)}")
    by_year = {}
    for q in qs:
        by_year[q["year"]] = by_year.get(q["year"], 0) + 1
    print("By year count:", by_year)
