def generate_eip_written_sessions():
    """
    정보처리기사 필기:
    - 2020~2026년 (7개 연도)
    - 연도별 정기 1회, 2회, 3회 (총 21개 회차)
    - 매 회차마다 100문항 (5개 과목 x 20문항)
    - 회차 내 중복 0건 엄격 보장
    """
    years = [2026, 2025, 2024, 2023, 2022, 2021, 2020]
    sessions = [1, 2, 3] # 정기 1회, 2회, 3회
    all_questions = []

    sub_configs = [
        (1, "1과목 소프트웨어 설계", SUB1_BANK),
        (2, "2과목 소프트웨어 개발", SUB2_BANK),
        (3, "3과목 데이터베이스 구축", SUB3_BANK),
        (4, "4과목 프로그래밍 언어 활용", SUB4_BANK),
        (5, "5과목 정보시스템 구축관리", SUB5_BANK)
    ]

    for y_idx, year in enumerate(years):
        for s_idx, session_num in enumerate(sessions):
            session_title = f"{year}년 제{session_num}회 정기기출"
            year_q_num = 1

            for sub_id, sub_name, bank in sub_configs:
                # 회차별로 서로 다른 20문항을 슬라이딩 선택
                # bank는 25문항 이상이므로, 매 회차마다 20개 고유 문항을 중복 없이 추출 가능
                bank_len = len(bank)
                start_offset = (y_idx * 5 + s_idx * 3) % bank_len
                
                selected_items = []
                for step in range(20):
                    item = bank[(start_offset + step) % bank_len]
                    selected_items.append(item)

                for item in selected_items:
                    q_id = f"eip-written-{year}-s{session_num}-{year_q_num:03d}"
                    all_questions.append({
                        "id": q_id,
                        "year": year,
                        "session": session_title,
                        "session_number": session_num,
                        "type": "multiple_choice",
                        "subject_id": sub_id,
                        "subject_name": sub_name,
                        "chapter": sub_name,
                        "question": item['q'],
                        "code_snippet": item.get("code"),
                        "options": item["opts"],
                        "answer": item["ans"],
                        "correct_answer": item["ans"],
                        "accepted_answers": None,
                        "explanation": item["exp"]
                    })
                    year_q_num += 1

    return all_questions

